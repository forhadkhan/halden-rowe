export type IconName = keyof typeof raw;

/** Inner markup of a Lucide icon (its paths), without the outer <svg> and licence comment. */
export function iconBody(name: IconName): string {
  const svg = raw[name];
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (body === undefined) throw new Error(`Lucide icon "${name}" could not be parsed.`);
  return body.trim();
}

